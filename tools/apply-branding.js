#!/usr/bin/env node
'use strict';

// Pushes product.json (the one place the product name lives) into the files that cannot read it
// at run time: Adobe manifests, installer scripts, native header, panel product.js.
//   node tools/apply-branding.js           rewrite files
//   node tools/apply-branding.js --check   exit 1 if any file is out of sync
// Idempotent. Protocol ids ("open-tethery" in /health, OTX1 magic) are not touched.

const fs = require('fs');
const path = require('path');

const xml = (t) => String(t).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const ps = (t) => String(t).replace(/'/g, "''");
const json = (t) => JSON.stringify(String(t)).slice(1, -1);
const iss = (t) => String(t).replace(/"/g, '""');
const cppW = (t) => Array.from(String(t), (c) => {
  const n = c.charCodeAt(0);
  if (n >= 32 && n < 127 && c !== '"' && c !== '\\' && c !== '?') return c;
  return '\\u' + n.toString(16).padStart(4, '0');
}).join('');

// Replace the first match of re; a miss means the file drifted from what this tool expects.
function rep(text, re, fn, file) {
  if (!re.test(text)) throw new Error(`${file}: pattern not found: ${re}`);
  return text.replace(re, (...m) => fn(...m));
}

function load(root) {
  const p = JSON.parse(fs.readFileSync(path.join(root, 'product.json'), 'utf8'));
  for (const k of ['name', 'shortName', 'vendor', 'version']) if (!p[k]) throw new Error(`product.json: "${k}" is required`);
  for (const k of ['cepBundle', 'cepExtension', 'uxp', 'helperExe', 'installDir', 'mediaCoreFolder', 'transmitPrm']) {
    if (!p.ids || !p.ids[k]) throw new Error(`product.json: ids.${k} is required`);
  }
  return p;
}

const productJs = (P) => `// GENERATED by tools/apply-branding.js from product.json. Do not edit.
(function (root) {
  var P = ${JSON.stringify({ name: P.name, shortName: P.shortName, vendor: P.vendor, version: P.version, updateUrl: P.updateUrl || '', ids: P.ids })};
  root.OT_PRODUCT = P;
  if (typeof module === 'object' && module.exports) module.exports = P;
})(typeof window !== 'undefined' ? window : globalThis);
`;

const productHeader = (P) => `// GENERATED by tools/apply-branding.js from product.json. Do not edit.
#pragma once
namespace pm {
constexpr const wchar_t* kProductName = L"${cppW(P.name)}";
// Name shown under Premiere Pro > Preferences > Playback > Video Device.
constexpr const wchar_t* kDisplayName = L"${cppW(P.name + ' (phone preview)')}";
// Audio output channel names (host copies them; keep short).
constexpr const wchar_t* kAudioNameL = L"${cppW(P.shortName + ' L')}";
constexpr const wchar_t* kAudioNameR = L"${cppW(P.shortName + ' R')}";
}  // namespace pm
`;

// [relative file, (text, P) => new text]. A file whose generator ignores `text` is fully generated.
function targets() {
  const defIss = (name, val) => [new RegExp(`^(#define ${name} ")[^"\\n]*(")`, 'm'), (m, a, b) => a + iss(val) + b];
  const defPs = (name, val) => [new RegExp(`^(\\$script:${name}\\s*= ')[^'\\n]*(')`, 'm'), (m, a, b) => a + ps(val) + b];
  const apply = (file, text, list) => list.reduce((t, [re, fn]) => rep(t, re, fn, file), text);
  const exeBase = (e) => e.replace(/\.exe$/i, '');
  return [
    ['panels/cep/CSXS/manifest.xml', (t, P) => apply('cep manifest', t, [
      [/(ExtensionBundleId=")[^"]*(")/, (m, a, b) => a + xml(P.ids.cepBundle) + b],
      [/(ExtensionBundleName=")[^"]*(")/, (m, a, b) => a + xml(P.name) + b],
      [/(<Author>)[^<]*(<\/Author>)/, (m, a, b) => a + xml(P.vendor) + b],
      [/(<Extension Id=")[^"]*(")/g, (m, a, b) => a + xml(P.ids.cepExtension) + b],
      [/(<Menu>)[^<]*(<\/Menu>)/, (m, a, b) => a + xml(P.name) + b],
    ])],
    ['panels/cep/.debug', (t, P) => apply('.debug', t, [
      [/(<Extension Id=")[^"]*(")/g, (m, a, b) => a + xml(P.ids.cepExtension) + b],
    ])],
    ['panels/uxp-photoshop/manifest.json', (t, P) => apply('uxp manifest', t, [
      [/("id": ")[^"]*(")/, (m, a, b) => a + json(P.ids.uxp) + b],
      [/("name": ")[^"]*(")/, (m, a, b) => a + json(P.name) + b],
      [/("default": ")[^"]*(")/, (m, a, b) => a + json(P.name) + b],
    ])],
    ['installer/version.txt', (t, P) => P.version + '\n'],
    ['installer/package.json', (t, P) => apply('installer/package.json', t, [
      [/("version": ")[^"]*(")/, (m, a, b) => a + json(P.version) + b],
    ])],
    ['installer/PocketMonitor.iss', (t, P) => apply('iss', t, [
      defIss('AppName', P.name), defIss('AppPublisher', P.vendor), defIss('InstallDirName', P.ids.installDir),
      defIss('PrmFile', P.ids.transmitPrm), defIss('HelperExe', P.ids.helperExe),
      defIss('RuleName', P.shortName + ' Helper'), defIss('RunValue', exeBase(P.ids.helperExe)),
      defIss('CepId', P.ids.cepBundle), defIss('PsPluginId', P.ids.uxp), defIss('MediaCoreFolder', P.ids.mediaCoreFolder),
    ])],
    ['installer/common.ps1', (t, P) => apply('common.ps1', t, [
      defPs('AppName', P.name), defPs('HelperExe', P.ids.helperExe), defPs('RuleName', P.shortName + ' Helper'),
      defPs('RunValueName', exeBase(P.ids.helperExe)), defPs('CepId', P.ids.cepBundle), defPs('PsPluginId', P.ids.uxp),
      defPs('MediaCoreName', P.ids.mediaCoreFolder), defPs('CcxName', P.ids.installDir + 'Photoshop.ccx'),
      defPs('PrmName', P.ids.transmitPrm),
      [/^(\$script:InstallDir\s*= Join-Path \$env:LOCALAPPDATA ')[^'\n]*(')/m, (m, a, b) => a + ps(P.ids.installDir) + b],
    ])],
    ['installer/start-helper.vbs', (t, P) => apply('start-helper.vbs', t, [
      [/^(' Starts )\S+( hidden)/, (m, a, b) => a + P.ids.helperExe + b],
      [/(dir & "\\)[^"]*\.exe(")/, (m, a, b) => a + P.ids.helperExe + b],
    ])],
    ['native/transmit/PocketMonitorTransmit.vcxproj', (t, P) => apply('vcxproj', t, [
      [/(<TargetName>)[^<]*(<\/TargetName>)/, (m, a, b) => a + xml(P.ids.transmitPrm.replace(/\.prm$/i, '')) + b],
    ])],
    ['native/transmit/src/ProductName.h', (t, P) => productHeader(P)],
    ['panels/cep/client/js/product.js', (t, P) => productJs(P)],
    ['site/brand.js', (t, P) => `// GENERATED by tools/apply-branding.js from product.json. Do not edit.\nwindow.PRODUCT = ${JSON.stringify({ name: P.name, version: P.version })};\n`],
    ['panels/uxp-photoshop/js/product.js', (t, P) => productJs(P)],
  ];
}

// Returns the list of files whose content differs (written unless check).
function run(root, { check = false } = {}) {
  const P = load(root);
  const changed = [];
  for (const [file, gen] of targets()) {
    const full = path.join(root, file);
    const old = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : '';
    const next = gen(old, P);
    if (next !== old) {
      changed.push(file);
      if (!check) {
        fs.mkdirSync(path.dirname(full), { recursive: true });
        fs.writeFileSync(full, next);
      }
    }
  }
  return changed;
}

module.exports = { run, targets, load };

if (require.main === module) {
  const check = process.argv.includes('--check');
  const root = path.resolve(__dirname, '..');
  try {
    const changed = run(root, { check });
    if (check) {
      if (changed.length) {
        console.error('Out of sync with product.json (run: node tools/apply-branding.js):\n  ' + changed.join('\n  '));
        process.exit(1);
      }
      console.log('Branding is in sync with product.json.');
    } else {
      console.log(changed.length ? 'Updated:\n  ' + changed.join('\n  ') : 'Already in sync.');
    }
  } catch (e) {
    console.error('ERROR:', e.message);
    process.exit(1);
  }
}
